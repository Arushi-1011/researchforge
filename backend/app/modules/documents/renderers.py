"""Safe HTML, PDF, and DOCX renderers from one normalized document structure."""
from html import escape
from io import BytesIO
from jinja2 import Environment, BaseLoader, select_autoescape
from docx import Document
from docx.shared import Inches


HTML_TEMPLATE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>{{ title }}</title>
<style>
body{font-family:Arial,sans-serif;color:#202336;line-height:1.5;margin:36px}
h1{color:#5141a5;border-bottom:2px solid #ded8ff;padding-bottom:10px}
h2{color:#5141a5;margin-top:26px} table{border-collapse:collapse;width:100%;font-size:10pt}
th,td{border:1px solid #d8d8e4;padding:7px;text-align:left;vertical-align:top}
th{background:#f1efff} .muted{color:#666} .paper{page-break-inside:avoid}
</style></head><body><h1>{{ title }}</h1>
<p class="muted">Generated by ResearchForge · {{ created_at }}</p>
{% for section in sections %}
<section><h2>{{ section["title"] }}</h2>
{% if section.get("kind") == "table" and section.get("rows") %}
<table><thead><tr>{% for head in section["headers"] %}<th>{{ head }}</th>{% endfor %}</tr></thead>
<tbody>{% for row in section["rows"] %}<tr>{% for cell in row %}<td>{{ cell }}</td>{% endfor %}</tr>{% endfor %}</tbody></table>
{% else %}
{% if section.get("items") %}
<ul>{% for item in section["items"] %}<li>{{ item }}</li>{% endfor %}</ul>
{% endif %}
{% if section.get("text") %}<p>{{ section["text"] }}</p>{% endif %}
{% if not section.get("items") and not section.get("text") %}<p class="muted">No data yet.</p>{% endif %}
{% endif %}
</section>
{% endfor %}
<p class="muted">AI insights, if included, are assistive and should be verified against original sources.</p>
</body></html>"""


def render_html(content: dict) -> str:
    env = Environment(loader=BaseLoader(), autoescape=select_autoescape(default=True, default_for_string=True))
    return env.from_string(HTML_TEMPLATE).render(**content)


def render_pdf(content: dict) -> bytes:
    from weasyprint import HTML
    return HTML(string=render_html(content), base_url=None).write_pdf()


def render_docx(content: dict) -> bytes:
    doc = Document()
    doc.add_heading(content["title"], level=0)
    doc.add_paragraph(f"Generated by ResearchForge · {content['created_at']}")
    for section in content["sections"]:
        doc.add_heading(section["title"], level=1)
        if section.get("kind") == "table" and section.get("rows"):
            table = doc.add_table(rows=1, cols=len(section["headers"]))
            table.style = "Table Grid"
            for cell, text in zip(table.rows[0].cells, section["headers"]):
                cell.text = str(text)
            for row in section["rows"]:
                cells = table.add_row().cells
                for cell, text in zip(cells, row):
                    cell.text = str(text)
        elif section.get("items"):
            for item in section["items"]:
                doc.add_paragraph(str(item), style="List Bullet")
        elif section.get("text"):
            doc.add_paragraph(str(section["text"]))
        else:
            doc.add_paragraph("No data yet.")
    stream = BytesIO()
    doc.save(stream)
    return stream.getvalue()
